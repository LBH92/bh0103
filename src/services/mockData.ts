// Helper to generate dynamic order book
export function generateOrderBook(stock: Stock) {
  const price = stock.price;
  const tick = price >= 100000 ? 500 : price >= 50000 ? 100 : 50;
  
  const asks = [];
  const bids = [];
  
  let totalAskVolume = 0;
  let totalBidVolume = 0;
  
  // 10 levels of asks (매도)
  for (let i = 10; i >= 1; i--) {
    const askPrice = price + i * tick;
    const vol = Math.round(1500 + Math.random() * 8000 * (11 - i));
    totalAskVolume += vol;
    const chg = askPrice - stock.prevClose;
    const chgPct = (chg / stock.prevClose) * 100;
    asks.push({
      price: askPrice,
      volume: vol,
      change: chg,
      changePercent: chgPct,
      barPercent: 0,
    });
  }
  
  // 10 levels of bids (매수)
  for (let i = 1; i <= 10; i++) {
    const bidPrice = price - (i - 1) * tick;
    const vol = Math.round(2000 + Math.random() * 9500 * (11 - i));
    totalBidVolume += vol;
    const chg = bidPrice - stock.prevClose;
    const chgPct = (chg / stock.prevClose) * 100;
    bids.push({
      price: bidPrice,
      volume: vol,
      change: chg,
      changePercent: chgPct,
      barPercent: 0,
    });
  }
  
  // Calculate bar percentages
  const maxVol = Math.max(...asks.map(a => a.volume), ...bids.map(b => b.volume), 1);
  asks.forEach(a => a.barPercent = Math.min(100, Math.round((a.volume / maxVol) * 100)));
  bids.forEach(b => b.barPercent = Math.min(100, Math.round((b.volume / maxVol) * 100)));
  
  return {
    symbol: stock.symbol,
    currentPrice: price,
    asks,
    bids,
    totalAskVolume,
    totalBidVolume,
  };
}
