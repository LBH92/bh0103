// Generate 30 days of realistic candles
function generateCandles(basePrice: number, volatility: number = 0.02, count: number = 30) {
  const candles = [];
  let price = basePrice * (1 - volatility * (count / 2));
  const now = new Date();
  
  for (let i = count; i >= 0; i--) {
    const d = new Date(now);
    d.setDate(d.getDate() - i);
    const dateStr = d.toISOString().split('T')[0];
    
    const change = (Math.random() - 0.48) * volatility * price;
    const open = Math.round(price);
    const close = Math.round(price + change);
    const high = Math.round(Math.max(open, close) + Math.random() * volatility * price * 0.8);
    const low = Math.round(Math.min(open, close) - Math.random() * volatility * price * 0.8);
    const volume = Math.round(500000 + Math.random() * 2500000);
    
    candles.push({
      time: dateStr,
      open,
      high,
      low,
      close,
      volume,
    });
    price = close;
  }
  return candles;
}

